// --- Tool Icon (props) ---
// every logo renders in the same square box; solid-square logos are drawn a little smaller
// and the tall Figma mark a little larger so they all look the same size
function ToolIcon({ icon, size = 16 }) {
  const box = size + 4
  const squareBox = Math.round(box * 0.85)
  switch (icon) {
    case 'figma':
      return <FigmaIcon size={Math.round(box * 1.1)} />
    case 'photoshop':
    case 'js':
    case 'xampp':
      return <BrandIcon name={icon} size={squareBox} />
    case 'mysql':
      return <MysqlIcon size={box} />
    case 'css':
      return <CssIcon size={box} />
    case 'flutter':
      return <FlutterIcon size={box} />
    case 'python':
      return <PythonIcon size={box} />
    case 'github':
      return <GitHubIcon size={box} />
    default:
      return brandPaths[icon] ? <BrandIcon name={icon} size={box} /> : null
  }
}

