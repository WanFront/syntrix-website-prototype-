// --- Tools Modal (props) ---
function ToolsModal({ isOpen, focusedTool, onClose }) {
  const itemRefs = useRef({})

  useEffect(() => {
    if (!isOpen || !focusedTool) return
    const el = itemRefs.current[focusedTool]
    el?.scrollIntoView({ block: 'center', behavior: 'smooth' })
  }, [isOpen, focusedTool])

  // --- Esc closes the pop-up ---
  useEffect(() => {
    if (!isOpen) return undefined
    const onKey = (e) => e.key === 'Escape' && onClose()
    window.addEventListener('keydown', onKey)
    return () => window.removeEventListener('keydown', onKey)
  }, [isOpen, onClose])

  if (!isOpen) return null

  return (
    <div className="ToolsModalOverlay" onClick={onClose}>
      <div className="ToolsModalCard" onClick={(e) => e.stopPropagation()}>
        <div className="ToolsModalHeader">
          <div>
            <h3 className="ToolsModalTitle">Our skills &amp; tools</h3>
            <p className="ToolsModalSubtitle">Categorized list of technical skills and development environments.</p>
          </div>
          <button onClick={onClose} className="ToolsModalCloseIcon" aria-label="Close">
            <X size={24} />
          </button>
        </div>

        <div className="ToolsModalBody">
          {/* --- map --- */}
          {toolCategories.map((category, i) => {
            const CategoryIcon = categoryIconMap[category.icon]
            const categoryTools = tools.filter((t) => t.category === category.name)
            const isLast = i === toolCategories.length - 1
            return (
              <div key={category.name} className={isLast ? 'ToolsModalCategory' : 'ToolsModalCategory ToolsModalCategoryDivided'}>
                <h4 className="ToolsModalCategoryTitle">
                  <CategoryIcon size={16} /> {category.name}
                </h4>
                <div className="ToolsModalGrid">
                  {/* --- map --- */}
                  {categoryTools.map((tool) => (
                    <div
                      key={tool.name}
                      ref={(el) => { itemRefs.current[tool.name] = el }}
                      className={`ToolsModalItem${tool.name === focusedTool ? ' ToolsModalItemFocused' : ''}`}
                    >
                      <div
                        className="ToolsModalItemIcon"
                        style={{ '--tool-bg': tool.background, '--tool-color': tool.color || '#1e293b', '--tool-border': tool.border || 'transparent' }}
                      >
                        <ToolIcon icon={tool.icon} size={20} />
                      </div>
                      <span className="ToolsModalItemName">{tool.name}</span>
                    </div>
                  ))}
                </div>
              </div>
            )
          })}
        </div>

        <div className="ToolsModalFooter">
          <span className="ToolsModalFooterText">{tools.length} core skills &amp; tools configured.</span>
          <button onClick={onClose} className="ToolsModalCloseBtn">Close</button>
        </div>
      </div>
    </div>
  )
}

